"""Command line entry points.

    python -m engine.cli init-db              create tables (dev/SQLite; use alembic in prod)
    python -m engine.cli gen-key              print a new ENGINE_ENCRYPTION_KEY
    python -m engine.cli cycle                run one full operation cycle in-process
    python -m engine.cli loop --minutes 15    run cycles forever (no Redis/Celery needed)
    python -m engine.cli demo-footage         generate owned synthetic test footage + rights records
    python -m engine.cli status               print operating mode and launch checklist
"""

from __future__ import annotations

import argparse
import json
import time

from . import db
from .config import get_settings
from .logs import configure_logging


def demo_footage(count: int = 4) -> list[int]:
    """Generate original test-pattern clips (owned by the operator) so the pipeline can run
    end to end without third-party material. Clearly labelled; never meant for publishing."""
    from .models import MediaAsset
    from .video import ffmpeg, footage

    settings = get_settings()
    out_dir = settings.data_dir / "footage" / "demo"
    out_dir.mkdir(parents=True, exist_ok=True)
    sources = [
        ("testsrc2=s=1920x1080:r=30", ["city", "night", "trailer", "detail", "vice", "leonida"]),
        ("mandelbrot=s=1920x1080:r=30", ["map", "beach", "location", "hidden", "theory"]),
        ("cellauto=s=1920x1080:r=30:rule=110", ["vehicle", "cars", "weapon", "gameplay"]),
        ("life=s=1920x1080:r=30:mold=10:ratio=0.1", ["characters", "lucia", "jason", "npc", "physics"]),
    ]
    ids = []
    with db.session_scope() as s:
        for i, (src, tags) in enumerate(sources[:count]):
            path = out_dir / f"demo_{i}.mp4"
            if not path.exists():
                ffmpeg.run(["-y", "-f", "lavfi", "-i", src, "-t", "20", "-vf", "format=yuv420p",
                            "-c:v", "libx264", "-preset", "veryfast", str(path)])
            existing = s.query(MediaAsset).filter_by(path=str(path.resolve())).first()
            if existing:
                ids.append(existing.id)
                continue
            a = footage.register_asset(
                s, path=str(path), kind="footage", original_source="generated by ffmpeg lavfi test source",
                owner="operator (generated locally)", licence="owned - synthetic test pattern",
                usage_permissions="testing only", allowed_platforms=["youtube", "tiktok", "instagram"],
                tags=tags, description="synthetic demo footage for pipeline testing: " + " ".join(tags),
                restrictions="TEST ONLY - not GTA footage, do not publish",
            )
            footage.verify_rights(a, actor="cli:demo-footage")
            ids.append(a.id)
    return ids


def main(argv: list[str] | None = None) -> None:
    configure_logging()
    parser = argparse.ArgumentParser(prog="engine")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init-db")
    sub.add_parser("gen-key")
    sub.add_parser("cycle")
    loop = sub.add_parser("loop")
    loop.add_argument("--minutes", type=float, default=15)
    sub.add_parser("demo-footage")
    sub.add_parser("status")
    args = parser.parse_args(argv)

    get_settings().ensure_dirs()
    if args.cmd == "gen-key":
        from .security import generate_encryption_key

        print(generate_encryption_key())
        return
    if args.cmd == "init-db":
        db.create_all()
        print("tables created")
        return
    db.create_all() if get_settings().database_url.startswith("sqlite") else None
    if args.cmd == "demo-footage":
        print(json.dumps({"asset_ids": demo_footage()}))
    elif args.cmd == "cycle":
        from .pipeline.scheduler import full_cycle

        print(json.dumps(full_cycle(), indent=2, default=str))
    elif args.cmd == "loop":
        from .pipeline.scheduler import full_cycle

        while True:
            print(json.dumps(full_cycle(), default=str))
            time.sleep(args.minutes * 60)
    elif args.cmd == "status":
        from .api.routes.control import checklist
        from .settings_store import get

        with db.session_scope() as s:
            print(json.dumps({"mode": get(s, "mode"), "publishing_paused": get(s, "publishing_paused"),
                              "checklist": checklist(s)}, indent=2))


if __name__ == "__main__":
    main()
